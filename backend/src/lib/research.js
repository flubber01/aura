'use strict';
// AURA Area 62 — Deep Research: real web research against api.github.com
// (allowed sandbox egress). Multi-query fan-out, dedupe, star-ranked synthesis.
// MODE: LIVE (real API data). No scraping of anything else, no auth needed.
const https = require('https');
const fs = require('fs');
const BASE = 'https://api.github.com';
const UA = { 'User-Agent': 'AURA-DeepResearch/1.0', 'Accept': 'application/vnd.github+json' };
const cache = new Map(); // q -> {at, results}
const TTL = 10 * 60 * 1000;
// system CA bundle (needed in proxied sandboxes, harmless on real servers)
let CA = null;
try { CA = fs.readFileSync('/etc/ssl/certs/ca-certificates.crt'); } catch {}

function httpsGetJson(pathname) {
  return new Promise((resolve, reject) => {
    const req = https.get({
      host: 'api.github.com', path: pathname, headers: UA, ca: CA || undefined, timeout: 9000,
    }, (res) => {
      let d = '';
      res.on('data', (c) => { d += c; if (d.length > 4e6) req.destroy(); });
      res.on('end', () => {
        try { resolve({ status: res.statusCode, json: JSON.parse(d) }); }
        catch (e) { reject(new Error('bad JSON (HTTP ' + res.statusCode + ')')); }
      });
    });
    req.on('timeout', () => { req.destroy(new Error('timeout')); });
    req.on('error', reject);
  });
}

// expand a topic into sub-queries (deterministic, transparent)
function fanout(topic) {
  const t = String(topic || '').trim().toLowerCase();
  if (!t) return [];
  const words = t.split(/[^a-z0-9äöüß-]+/).filter(Boolean);
  const qs = new Set([t]);
  if (words.length > 1) {
    qs.add(words.slice(0, 2).join(' '));
    qs.add(words.slice(-2).join(' '));
  }
  for (const suf of ['agent', 'framework', 'cli', 'api']) {
    if (!t.includes(suf) && words.length) qs.add(words[0] + ' ' + suf);
  }
  return [...qs].slice(0, 5);
}

async function ghSearch(q, perPage) {
  const pathname = '/search/repositories?q=' + encodeURIComponent(q) +
    '&sort=stars&order=desc&per_page=' + perPage;
  try {
    const { status, json } = await httpsGetJson(pathname);
    if (status !== 200) return { q, error: 'HTTP ' + status, items: [] };
    return {
      q,
      items: (json.items || []).map((it) => ({
        name: it.full_name,
        url: it.html_url,
        stars: it.stargazers_count,
        lang: it.language || '-',
        pushed: (it.pushed_at || '').slice(0, 10),
        desc: String(it.description || '').slice(0, 180),
        topics: (it.topics || []).slice(0, 6),
        license: (it.license && it.license.spdx_id) || 'n/a',
      })),
    };
  } catch (e) {
    return { q, error: String(e.message || e), items: [] };
  }
}

async function research(topic, opts) {
  const o = opts || {};
  const perPage = Math.min(20, Math.max(3, Number(o.perQuery) || 8));
  const queries = fanout(topic);
  if (!queries.length) return { ok: false, error: 'topic required' };
  const key = queries.join('|') + ':' + perPage;
  if (cache.has(key) && Date.now() - cache.get(key).at < TTL && !o.nocache) {
    return Object.assign({ cached: true }, cache.get(key).data);
  }
  const batches = await Promise.all(queries.map((q) => ghSearch(q, perPage)));
  // dedupe by repo name, keep highest stars, record which sub-query found it
  const seen = new Map();
  for (const b of batches) {
    for (const it of b.items) {
      if (!seen.has(it.name) || seen.get(it.name).stars < it.stars) {
        seen.set(it.name, Object.assign({ foundVia: b.q }, it));
      }
    }
  }
  const results = [...seen.values()].sort((a, b) => b.stars - a.stars).slice(0, 40);
  const synthesis = {
    total: results.length,
    topStar: results[0] ? results[0].stars : 0,
    languages: {},
    activeLast90d: results.filter((r) => r.pushed && (Date.now() - new Date(r.pushed).getTime()) < 90 * 864e5).length,
  };
  for (const r of results) synthesis.languages[r.lang] = (synthesis.languages[r.lang] || 0) + 1;
  const data = {
    ok: true, mode: 'LIVE', source: 'api.github.com', topic,
    queries, subQueryErrors: batches.filter((b) => b.error).map((b) => ({ q: b.q, error: b.error })),
    synthesis, results, at: new Date().toISOString(),
  };
  cache.set(key, { at: Date.now(), data });
  return data;
}

function toMarkdown(rep) {
  const L = ['# AURA Deep Research — ' + rep.topic, '',
    'Mode: ' + rep.mode + ' · source: ' + rep.source + ' · ' + rep.at, '',
    'Sub-queries: ' + rep.queries.join(' | '), '',
    '## Top results (' + rep.synthesis.total + ')', ''];
  rep.results.slice(0, 25).forEach((r, i) => {
    L.push(i + 1 + '. **' + r.name + '** — ★' + r.stars + ' · ' + r.lang + ' · pushed ' + r.pushed + ' · [' + r.url + '](' + r.url + ')');
    if (r.desc) L.push('   ' + r.desc);
  });
  L.push('', '_Generated by AURA Deep Research (Area 62). Real data, no hallucination._');
  return L.join('\n');
}

module.exports = {
  meta: { area: '62', id: 'deep_research', name: 'Deep Research (live GitHub-API fan-out)', state: 'live' },
  research, toMarkdown, fanout,
  actions: {
    status: () => ({ mode: 'LIVE', source: 'api.github.com', cached_queries: cache.size, ttl_min: TTL / 60000 }),
  },
};
